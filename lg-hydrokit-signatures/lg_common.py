def ta_alias(house: str) -> LeftRightDot:
    """The terminal asset alias of a Millinocket house by its short name."""
    return TypeAdapter(LeftRightDot).validate_python(f"hw1.isone.me.versant.keene.{house}.ta")


def regen_path(house: str) -> Path:
    """The house's pull, regenerated by pull.py, gitignored."""
    return HERE / f"{ta_alias(house)}-{START:%Y%m%d}.{END:%Y%m%d}-lg.readings-regen.npz"


class Channel(NamedTuple):
    """One channel's readings in natural units, time ordered."""

    t_ms: np.ndarray  # UTC ms, int64
    value: np.ndarray  # natural units, float64


def load(house: str) -> dict[str, Channel]:
    """Every channel of the house's pull."""
    z = np.load(regen_path(house))
    names = sorted({k.rsplit("__", 1)[0] for k in z.files})
    return {n: Channel(z[f"{n}__t"], z[f"{n}__v"]) for n in names}


class Grid(NamedTuple):
    """The house's channels on one time step, NaN where stale."""

    t_ms: np.ndarray
    step_s: int
    odu: np.ndarray
    idu: np.ndarray
    lwt: np.ndarray
    ewt: np.ndarray
    flow: np.ndarray
    r6: np.ndarray
    foat: np.ndarray

    @property
    def lift(self) -> np.ndarray:
        return self.lwt - self.ewt

    @property
    def total(self) -> np.ndarray:
        return self.odu + self.idu


def on_grid_capped(ch: Channel | None, t_ms: np.ndarray, stale_s: float) -> np.ndarray:
    """Forward-fill one channel onto t_ms, NaN where its reading is older
    than stale_s or the channel has none yet."""
    if ch is None or len(ch.t_ms) == 0:
        return np.full(len(t_ms), np.nan)
    idx = np.searchsorted(ch.t_ms, t_ms, side="right") - 1
    seen = idx >= 0
    idx = np.clip(idx, 0, None)
    age_s = (t_ms - ch.t_ms[idx]) / 1000.0
    return np.where(seen & (age_s <= stale_s), ch.value[idx], np.nan)


def grid(house: str, step_s: int) -> Grid:
    """The house's whole pull on a step_s grid."""
    chans = load(house)
    t0 = min(c.t_ms[0] for c in chans.values() if len(c.t_ms))
    t1 = max(c.t_ms[-1] for c in chans.values() if len(c.t_ms))
    t = np.arange(t0 - t0 % (step_s * 1000) + step_s * 1000, t1, step_s * 1000, dtype=np.int64)
    f = {n: on_grid_capped(chans.get(n), t, STALE_S[n]) for n in (ODU, IDU, LWT, EWT, FLOW, R6, FOAT)}
    return Grid(t, step_s, f[ODU], f[IDU], f[LWT], f[EWT], f[FLOW], f[R6], f[FOAT])


def segments(mask: np.ndarray) -> list[tuple[int, int]]:
    """(start, end) index pairs, end exclusive, of each run of True."""
    d = np.diff(np.r_[0, mask.astype(np.int8), 0])
    return list(zip(np.where(d == 1)[0].tolist(), np.where(d == -1)[0].tolist()))


def quantiles(x: np.ndarray, ps: tuple[float, ...] = (0.1, 0.5, 0.9)) -> str:
    """p10 / median / p90 of the finite values, with their count."""
    v = x[np.isfinite(x)]
    if len(v) == 0:
        return "n=0"
    return " / ".join(f"{q:.1f}" for q in np.quantile(v, ps)) + f" (n={len(v)})"
