"""What this folder's scripts share: the two LG houses, the channels
pulled, the window, the run thresholds, and the regen pull read back
onto a grid in natural units.

The pull (`pull.py`) writes one `-regen.npz` per house: for each
channel, reading times (UTC ms) and values already in natural units
(W, °F, gpm, relay 0/1). `grid` forward-fills those readings onto a
fixed step and blanks any sample whose reading is older than the
channel's staleness cap, so a silent channel reads NaN.

No sema word holds a forward-filled grid of channel readings; a word
for aggregated channel readings retires the npz form and this module.

Unfinished: exercised only by import; no pull has been loaded through it yet.
"""

