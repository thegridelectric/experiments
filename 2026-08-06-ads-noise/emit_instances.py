#!/usr/bin/env python3
"""Emit sema-typed instances for the ads-noise canary datasets.

Instances (see README "Canary datasets" + the semafy-experiments design):
  instances/2026-08-06-clean-harness/gw.experiment.run-000.json
  instances/2026-08-06-clean-harness/<channel>.<mode>.gw.channel.noise.stats.000.json
      x24 — per read mode, uV stats paired with the -gw-microvolts
      channel and temperature stats with the -gw-temp channel, both
      recomputed from the raw per-sample capture (filter output for the
      EMA mode, post-warmup)
  instances/2026-07-22-clean-archive/<channel>.gw.channel.jump.stats.000.json x4
  instances/2026-07-26-glitch-archive/<channel>.gw.channel.jump.stats.000.json x4

Instances are constructed THROUGH the generated sema snapshot
(src/gwexp/sema, regenerated by ../regen_sema_snapshot.sh) so schema and
axioms validate at construction — never as hand-built dicts.
Kind-specific bench structure (mode knobs, per-mode channel statistics,
board provenance) stays in the plain results-summary files — no per-kind
words. Sources, all sema-typed: the archive readings come from this
folder's gw.readings instance (channel words + readings together); the
noise-stats channel pairings and the host GNode alias come from the
scada's own layout.lite emission (immutable store, fetched to this
folder); the thermistor constants come from the reader-component
instance extracted alongside it. Nothing reads the legacy layout
envelope.
"""

import datetime
import json
import math
import statistics
import sys
from pathlib import Path
from zoneinfo import ZoneInfo

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "src"))
sys.path.insert(0, str(HERE.parent))

from gwexp.sema.codec import SemaCodec  # noqa: E402
from gwexp.sema.types import (  # noqa: E402
    GwChannelJumpStats,
    GwChannelNoiseStats,
    GwExperimentRun,
    GwReadings,
    LayoutLite,
)
from gwexp.sema.types.old_versions.i2c_thermistor_reader_component_gt_000 import (  # noqa: E402
    I2cThermistorReaderComponentGt000,
)
from gwexp.sema.types.old_versions.layout_lite_012 import LayoutLite012  # noqa: E402
from naming import spaceheat_name_to_lrd_token  # noqa: E402

ET = ZoneInfo("America/New_York")
LAYOUT_LITE = HERE / ("hw1.isone.me.versant.keene.spruce.scada"
                      "-layout.lite-1786028416399-hw1.ear.json")
READER_PATH = HERE / "i2c.thermistor.reader.component.gt-000.json"
PULL_PATH = HERE / "hw1.isone.me.versant.keene.spruce.ta-gw.readings-000.json"

# HAND-CODED because no deployed sema layout declares zone sensing
# modality yet: spruce's thermistor-sensed zones (zone5-living-rm-fancoil
# is opto-only — no thermistor, no ADS channel — and deliberately absent).
# Replace with a layout query when the sema layout deploys.
THERMISTOR_ZONES = ["zone1-bedrooms", "zone2-living-rm",
                    "zone3-upstairs", "zone4-garage"]

JUMP_THRESHOLD_UV = 50_000
MAX_GAP_S = 300


def et_ms(s: str) -> int:
    return int(datetime.datetime.fromisoformat(s).replace(tzinfo=ET).timestamp() * 1000)


def load_layout_lite():
    """The scada's own layout.lite emission live at the clean run
    (eventstore object, gw envelope), decoded through the codec at its
    emitted version."""
    payload = json.loads(LAYOUT_LITE.read_text())["Payload"]
    layout = SemaCodec().from_dict(payload, auto_upgrade=False)
    assert isinstance(layout, (LayoutLite, LayoutLite012))
    return layout


def host_gnode_alias(layout) -> str:
    return layout.from_g_node_alias


def channel_words(layout):
    """ChannelName -> the channel's sema word, as the scada emitted it
    (no upgrade: the pairing records what the channel was declared
    under)."""
    return {c.name: c for c in list(layout.data_channels)
            + list(layout.derived_channels)}


def load_pull() -> GwReadings:
    """This folder's archive pull: the zone microvolt channels' words
    and readings over 07-14 -> 08-06, as one validated instance."""
    return SemaCodec().from_dict(json.loads(PULL_PATH.read_text()),
                                 expect=GwReadings)


def clean_harness_run(layout) -> GwExperimentRun:
    ts = [json.loads(line)["t"]
          for line in open(HERE / "raw-samples-2026-08-06-clean.jsonl")]
    return GwExperimentRun(
        experiment_slug="ads-noise",
        host_g_node_alias=host_gnode_alias(layout),
        start_unix_ms=int(min(ts) * 1000),
        end_unix_ms=int(max(ts) * 1000),
        code_ref="ads_noise_experiment.py",
    )


def jump_stats(pull: GwReadings, name: str, start_ms: int,
               end_ms: int) -> GwChannelJumpStats:
    """Jump statistics for one channel over [start_ms, end_ms): count
    consecutive-reading jumps above JUMP_THRESHOLD_UV, ignoring pairs
    more than MAX_GAP_S apart (a jump across a reporting gap is a gap
    artifact, not a spike). Words and readings both come from the
    pull instance; the stats speak the channel's serialized units."""
    chan = f"{name}-gw-microvolts"
    word = next(c for c in pull.channels if c.name == chan)
    readings = next(r for r in pull.channel_readings_list
                    if r.channel_name == chan)
    pairs = [(t, v) for t, v in zip(readings.scada_read_time_unix_ms_list,
                                    readings.value_list)
             if start_ms <= t < end_ms]
    jumps = [abs(v1 - v0) for (t0, v0), (t1, v1) in zip(pairs, pairs[1:])
             if (t1 - t0) / 1000 < MAX_GAP_S]
    w = pairs
    return GwChannelJumpStats(
        channel_name=chan,
        channel_type_name=word.type_name,
        channel_version=word.version,
        window_start_unix_ms=start_ms,
        window_end_unix_ms=end_ms,
        num_readings=len(w),
        jump_threshold=JUMP_THRESHOLD_UV,
        max_gap_s=MAX_GAP_S,
        spike_count=sum(1 for j in jumps if j > JUMP_THRESHOLD_UV),
        max_abs_jump=max(jumps) if jumps else 0,
        median_abs_jump=float(statistics.median(jumps)) if jumps else 0.0,
    )


EMA_WARMUP = 25  # matches the harness: EMA convergence tail discarded


def reader_record():
    """The thermistor-reader component instance (extracted from the
    box layout the runs consumed; layout.lite does not carry reader
    components), decoded at its own version — it holds the electrical
    constants the temp conversion needs."""
    return SemaCodec().from_dict(json.loads(READER_PATH.read_text()),
                                 auto_upgrade=False,
                                 expect=I2cThermistorReaderComponentGt000)


def simple_beta_temp(uv: float, beta: int, vref: float, series_kohms: float) -> float | None:
    """SimpleBeta sensing conversion: microvolts -> physical temperature
    in C, mirroring the harness. Wire encoding (CelsiusTimes100) is
    applied where the instance is constructed, not here."""
    volts = uv / 1e6
    if volts <= 0.01 or volts >= vref:
        return None
    r = series_kohms * volts / (vref - volts)
    return 1 / ((1 / 298.15) + (math.log(r / 10) / beta)) - 273


def noise_stats_instances(words) -> list[tuple[str, GwChannelNoiseStats]]:
    reader = reader_record()
    assert reader.temp_calc_method.value == "SimpleBeta"
    betas = {}
    for c in reader.config_list:
        zone = c.channel_name.removesuffix("-gw-temp").removesuffix("-gw-microvolts")
        betas[zone] = c.thermistor_beta

    samples: dict[tuple[str, str], list[dict]] = {}
    for line in open(HERE / "raw-samples-2026-08-06-clean.jsonl"):
        r = json.loads(line)
        if "err" in r:
            continue
        samples.setdefault((r["mode"], r["chan"]), []).append(r)

    out = []
    for (mode, zone), recs in samples.items():
        # Filter output for the EMA mode (post-warmup), raw otherwise.
        if "ema_uv" in recs[0]:
            series = [r["ema_uv"] for r in recs[EMA_WARMUP:]]
            window = recs[EMA_WARMUP:]
        else:
            series = [r["uv"] for r in recs]
            window = recs
        start_ms = int(window[0]["t"] * 1000)
        end_ms = int(window[-1]["t"] * 1000)
        for suffix, values in [
            ("-gw-microvolts", series),
            # x100: the -gw-temp channel's wire encoding (CelsiusTimes100)
            ("-gw-temp", [t * 100 for t in (
                simple_beta_temp(uv, betas[zone], reader.adc_reference_volts,
                          reader.series_resistance_k_ohms) for uv in series)
                if t is not None]),
        ]:
            chan = f"{zone}{suffix}"
            word = words[chan]
            out.append((f"{spaceheat_name_to_lrd_token(chan)}-{spaceheat_name_to_lrd_token(mode)}", GwChannelNoiseStats(
                channel_name=chan,
                channel_type_name=word.type_name,
                channel_version=word.version,
                condition_label=mode,
                window_start_unix_ms=start_ms,
                window_end_unix_ms=end_ms,
                num_samples=len(values),
                mean=round(statistics.mean(values), 1),
                sd=round(statistics.stdev(values), 3),
                p2p=round(max(values) - min(values), 1),
            )))
    return out


def write(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj.to_dict(), indent=1) + "\n")
    print(f"wrote {path.relative_to(HERE)}")


def main() -> None:
    layout = load_layout_lite()
    write(HERE / "instances/2026-08-06-clean-harness/gw.experiment.run-000.json",
          clean_harness_run(layout))

    words = channel_words(layout)
    pull = load_pull()
    for name, inst in noise_stats_instances(words):
        write(HERE / f"instances/2026-08-06-clean-harness/{name}-gw.channel.noise.stats-000.json",
              inst)
    for slug, a, b in [
        ("2026-07-22-clean-archive", "2026-07-22 00:00", "2026-07-23 00:00"),
        ("2026-07-26-glitch-archive", "2026-07-26 20:30", "2026-07-26 23:15"),
    ]:
        for chan in THERMISTOR_ZONES:
            j = jump_stats(pull, chan, et_ms(a), et_ms(b))
            write(HERE / f"instances/{slug}/{spaceheat_name_to_lrd_token(j.channel_name)}-gw.channel.jump.stats-000.json", j)


if __name__ == "__main__":
    main()
