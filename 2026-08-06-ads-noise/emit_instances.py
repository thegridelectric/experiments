#!/usr/bin/env python3
"""Emit sema-typed instances for the ads-noise canary datasets.

Instances (see README "Canary datasets" + the semafy-experiments design):
  instances/2026-08-06-clean-bench/gw.experiment.run.json
  instances/2026-07-22-clean-archive/<channel>.gw.channel.jump.stats.json x4
  instances/2026-07-26-glitch-archive/<channel>.gw.channel.jump.stats.json x4

Instances are constructed THROUGH the generated sema snapshot
(src/gwexp/sema, regenerated by ../regen_sema_snapshot.sh) so schema and
axioms validate at construction — never as hand-built dicts.
Kind-specific bench structure (mode knobs, per-mode channel statistics,
board provenance) stays in the plain results-summary files — no per-kind
words. The host GNode alias and each channel's declaring word come from
the archived hardware layout in this folder, not hardcoded strings.
"""

import csv
import datetime
import json
import statistics
import sys
from pathlib import Path
from zoneinfo import ZoneInfo

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "src"))

from gwexp.sema.types import GwChannelJumpStats, GwExperimentRun  # noqa: E402

ET = ZoneInfo("America/New_York")
ARCHIVE = HERE / "archive-zone-uv-2026-07-14-to-08-06.csv"
LAYOUT = HERE / "spruce-hardware-layout-2026-08-05.json"
CHANNELS = ["zone1-bedrooms", "zone2-living-rm", "zone3-upstairs", "zone4-garage"]

JUMP_THRESHOLD_UV = 50_000
MAX_GAP_S = 300


def et_ms(s: str) -> int:
    return int(datetime.datetime.fromisoformat(s).replace(tzinfo=ET).timestamp() * 1000)


def host_gnode_alias() -> str:
    return json.loads(LAYOUT.read_text())["MyScadaGNode"]["Alias"]


def channel_words() -> dict[str, tuple[str, str]]:
    """ChannelName -> (TypeName, Version) of the word declaring it,
    from the archived layout — the stats travel with the channel's own
    sema object rather than restating its units."""
    layout = json.loads(LAYOUT.read_text())
    return {
        ch["Name"]: (ch["TypeName"], ch["Version"])
        for ch in layout["DataChannels"]
    }


def load_archive():
    rows = {c: [] for c in CHANNELS}
    with open(ARCHIVE) as f:
        for r in csv.DictReader(f):
            chan = r["channel"].removesuffix("-gw-microvolts")
            if chan in rows:
                t = datetime.datetime.fromisoformat(r["timestamp_et"]).replace(tzinfo=ET)
                rows[chan].append((t, int(float(r["value"]))))
    for series in rows.values():
        series.sort()
    return rows


def clean_bench_run() -> GwExperimentRun:
    ts = [json.loads(line)["t"]
          for line in open(HERE / "raw-samples-2026-08-06-clean.jsonl")]
    return GwExperimentRun(
        experiment_slug="ads-noise",
        host_g_node_alias=host_gnode_alias(),
        start_unix_ms=int(min(ts) * 1000),
        end_unix_ms=int(max(ts) * 1000),
        code_ref="ads_noise_experiment.py",
    )


def jump_stats(name: str, series, start_ms: int, end_ms: int,
               words: dict[str, tuple[str, str]]) -> GwChannelJumpStats:
    w = [(t, v) for t, v in series
         if start_ms <= t.timestamp() * 1000 < end_ms]
    jumps = [abs(v1 - v0) for (t0, v0), (t1, v1) in zip(w, w[1:])
             if (t1 - t0).total_seconds() < MAX_GAP_S]
    chan = f"{name}-gw-microvolts"
    type_name, version = words[chan]
    return GwChannelJumpStats(
        channel_name=chan,
        channel_type_name=type_name,
        channel_version=version,
        window_start_unix_ms=start_ms,
        window_end_unix_ms=end_ms,
        num_readings=len(w),
        jump_threshold=JUMP_THRESHOLD_UV,
        max_gap_s=MAX_GAP_S,
        spike_count=sum(1 for j in jumps if j > JUMP_THRESHOLD_UV),
        max_abs_jump=max(jumps) if jumps else 0,
        median_abs_jump=float(statistics.median(jumps)) if jumps else 0.0,
    )


def write(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj.to_dict(), indent=1) + "\n")
    print(f"wrote {path.relative_to(HERE)}")


def main() -> None:
    write(HERE / "instances/2026-08-06-clean-bench/gw.experiment.run.json",
          clean_bench_run())

    rows = load_archive()
    words = channel_words()
    for slug, a, b in [
        ("2026-07-22-clean-archive", "2026-07-22 00:00", "2026-07-23 00:00"),
        ("2026-07-26-glitch-archive", "2026-07-26 20:30", "2026-07-26 23:15"),
    ]:
        for chan in CHANNELS:
            j = jump_stats(chan, rows[chan], et_ms(a), et_ms(b), words)
            write(HERE / f"instances/{slug}/{chan}.gw.channel.jump.stats.json", j)


if __name__ == "__main__":
    main()
